import { PHYSIO_MCP_TOOLS } from "./contract.js";
import { programRowInputSchema } from "./json-schema.js";

const WRITE = new Set([
  "create_or_edit_program",
  "publish_program",
  "set_program_link_expiry",
  "delete_program",
]);

export const OMITTED_WRITE_TOOL_DESCRIPTIONS = [
  {
    tool: "create_or_edit_program",
    note: "No approved MCP tool description (#25–#27 in spec PR132 / DIDI-1251 cover publish, set expiry, and delete only).",
  },
] as const;

export type OmissionPathRow = { tool: string; side: string; path: string };

export function collectWriteSchemaOmissionPaths(): OmissionPathRow[] {
  const rows: OmissionPathRow[] = [];

  function walk(node: unknown, prefix: string, tool: string, side: string): void {
    if (!node || typeof node !== "object") return;
    const n = node as Record<string, unknown>;
    if (n.properties && typeof n.properties === "object") {
      for (const [k, v] of Object.entries(n.properties as Record<string, unknown>)) {
        const p = prefix ? `${prefix}.${k}` : k;
        if (v && typeof v === "object") {
          const leaf = v as Record<string, unknown>;
          if (!Object.prototype.hasOwnProperty.call(leaf, "description")) {
            rows.push({ tool, side, path: p });
          }
          walk(v, p, tool, side);
        }
      }
    }
    if (n.items) walk(n.items, `${prefix}[]`, tool, side);
    if (Array.isArray(n.oneOf)) for (const b of n.oneOf) walk(b, prefix, tool, side);
    if (Array.isArray(n.allOf)) for (const b of n.allOf) walk(b, prefix, tool, side);
  }

  for (const t of PHYSIO_MCP_TOOLS) {
    if (!WRITE.has(t.name)) continue;
    walk(t.inputSchema, "", t.name, "input");
    walk(t.outputSchema, "", t.name, "output");
  }
  walk(programRowInputSchema, "rows[]", "create_or_edit_program", "input");

  const seen = new Set<string>();
  return rows
    .filter((r) => {
      const k = `${r.tool}|${r.side}|${r.path}`;
      if (seen.has(k)) return false;
      seen.add(k);
      return true;
    })
    .sort(
      (a, b) =>
        a.tool.localeCompare(b.tool) ||
        a.side.localeCompare(b.side) ||
        a.path.localeCompare(b.path),
    );
}

export function buildWriteSchemaOmissionsMarkdown(): {
  markdown: string;
  paths: OmissionPathRow[];
  total: number;
} {
  const unique = collectWriteSchemaOmissionPaths();

  let md = "# Write-tool schema fields without `description`\n\n";
  md +=
    "Generated by `npx tsx scripts/list-mcp-write-schema-omissions.ts` from `PHYSIO_MCP_TOOLS` write tools. Read-tool schemas are unchanged.\n\n";
  md +=
    "## Omitted MCP tool descriptions\n\nConfirm instruction is approved in tool descriptions #25–#27 (spec PR132, merge `5c02d0b`).\n\n";
  for (const o of OMITTED_WRITE_TOOL_DESCRIPTIONS) {
    md += `- \`${o.tool}\`: ${o.note}\n`;
  }
  md += "\n## Omitted schema `description` paths\n\n";
  for (const r of unique) {
    md += `- \`${r.tool}\` ${r.side}: \`${r.path}\`\n`;
  }
  md += `\nTotal: ${unique.length} paths.\n`;

  return { markdown: md, paths: unique, total: unique.length };
}
