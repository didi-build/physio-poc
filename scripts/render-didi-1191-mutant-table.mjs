#!/usr/bin/env node
import { readFileSync, writeFileSync } from "node:fs";

const [logPath, tablePath, baselineSha] = process.argv.slice(2);
if (!logPath || !tablePath || !baselineSha) {
  console.error("usage: render-didi-1191-mutant-table.mjs <runs.log> <table.md> <sha>");
  process.exit(1);
}

const text = readFileSync(logPath, "utf8");
const blocks = text.split(/^=== (M\d+) ===$/m).slice(1);
const rows = [];

for (let i = 0; i < blocks.length; i += 2) {
  const id = blocks[i];
  const body = blocks[i + 1] ?? "";
  const failLines = [...body.matchAll(/^ FAIL\s+(.+)$/gm)].map((match) =>
    match[1].trim(),
  );
  const killed = failLines.length > 0 ? "killed" : "survived";
  rows.push({ id, killed, failLines });
}

const lines = [
  `# DIDI-1191 mutation table`,
  "",
  `Generated by \`scripts/run-didi-1191-mutants.sh\` at baseline \`${baselineSha}\`.`,
  "",
  "| Mutant | Result | Failing tests |",
  "| --- | --- | --- |",
  ...rows.map((row) => {
    const tests =
      row.failLines.length === 0
        ? "(none)"
        : row.failLines.map((name) => `\`${name}\``).join("; ");
    return `| ${row.id} | ${row.killed} | ${tests} |`;
  }),
  "",
];

writeFileSync(tablePath, lines.join("\n"));
