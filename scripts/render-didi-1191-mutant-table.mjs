#!/usr/bin/env node
import { readFileSync, writeFileSync } from "node:fs";

const [logPath, tablePath, baselineSha] = process.argv.slice(2);
if (!logPath || !tablePath || !baselineSha) {
  console.error(
    "usage: render-didi-1191-mutant-table.mjs <runs.log> <table.md> <full-sha>",
  );
  process.exit(1);
}

const DIDI_1191_KILL =
  /program-publish-didi-1191|worker-public-share-link-media-didi-1191|public-link-page-didi-1191|public-link-carousel-didi-1191/;

const text = readFileSync(logPath, "utf8");
const blocks = text.split(/^=== (M\d+) ===$/m).slice(1);
const sections = [];
const summaryRows = [];

for (let i = 0; i < blocks.length; i += 2) {
  const id = blocks[i];
  const body = blocks[i + 1] ?? "";

  const description =
    body.match(/^description: (.+)$/m)?.[1]?.trim() ?? "(missing description)";
  const diffNonempty = body.match(/^diff_nonempty: (yes|NO)$/m)?.[1] ?? "?";
  const suiteExit = body.match(/^suite_exit: (\d+)$/m)?.[1] ?? "?";
  const revertExit = body.match(/^revert_exit: (\d+)$/m)?.[1] ?? "?";
  const testFilesLine = body.match(/^Test Files\s+(.+)$/m)?.[1]?.trim() ?? "";
  const testsLine = body.match(/^Tests\s+(.+)$/m)?.[1]?.trim() ?? "";

  const failLines = [...body.matchAll(/^ FAIL\s+(.+)$/gm)].map((m) => m[1].trim());
  const kills = failLines.filter((name) => DIDI_1191_KILL.test(name));
  const noise = failLines.filter((name) => !DIDI_1191_KILL.test(name));

  let result;
  if (diffNonempty === "NO") {
    result = "not applied";
  } else if (kills.length > 0) {
    result = "killed";
  } else if (failLines.length > 0) {
    result = "survived (noise only)";
  } else {
    result = "survived";
  }

  summaryRows.push({ id, description, result, kills, noise, suiteExit, revertExit });

  const diffStat = (() => {
    const start = body.indexOf("--- diff stat ---");
    const mid = body.indexOf("--- diff ---");
    const end = body.indexOf("--- suite ---");
    if (start === -1 || mid === -1 || end === -1) {
      return "(missing diff stat)";
    }
    return body.slice(start + "--- diff stat ---".length, mid).trim();
  })();

  const diffHunk = (() => {
    const start = body.indexOf("--- diff ---");
    const end = body.indexOf("--- suite ---");
    if (start === -1 || end === -1) {
      return "(missing diff hunk)";
    }
    return body.slice(start + "--- diff ---".length, end).trim();
  })();

  sections.push(
    [
      `## ${id}`,
      "",
      description,
      "",
      `| Field | Value |`,
      `| --- | --- |`,
      `| Result | ${result} |`,
      `| diff_nonempty | ${diffNonempty} |`,
      `| suite_exit | ${suiteExit} |`,
      `| test_files | ${testFilesLine || "(n/a)"} |`,
      `| tests | ${testsLine || "(n/a)"} |`,
      `| revert_exit | ${revertExit} |`,
      `| DIDI-1191 kills | ${kills.length ? kills.map((t) => `\`${t}\``).join("; ") : "(none)"} |`,
      `| Noise | ${noise.length ? noise.map((t) => `\`${t}\``).join("; ") : "(none)"} |`,
      "",
      "### diff --stat",
      "",
      "```",
      diffStat || "(empty)",
      "```",
      "",
      "### diff hunk",
      "",
      "```diff",
      diffHunk || "(empty)",
      "```",
      "",
    ].join("\n"),
  );
}

const survived = summaryRows.filter(
  (row) => row.result === "survived" || row.result === "survived (noise only)",
);
const notApplied = summaryRows.filter((row) => row.result === "not applied");

const lines = [
  `# DIDI-1191 mutation report`,
  "",
  `Generated by \`scripts/run-didi-1191-mutants.sh\` at baseline \`${baselineSha}\`.`,
  "",
  `Summary: ${summaryRows.filter((r) => r.result === "killed").length} killed; ${survived.length} survived; ${notApplied.length} not applied.`,
  "",
  "| Mutant | Description | Result | DIDI-1191 kills | Noise | suite_exit | revert_exit |",
  "| --- | --- | --- | --- | --- | --- | --- |",
  ...summaryRows.map((row) => {
    const killCell =
      row.kills.length === 0 ? "(none)" : row.kills.map((t) => `\`${t}\``).join("; ");
    const noiseCell =
      row.noise.length === 0 ? "(none)" : row.noise.map((t) => `\`${t}\``).join("; ");
    const desc = row.description.replace(/\|/g, "\\|");
    return `| ${row.id} | ${desc} | ${row.result} | ${killCell} | ${noiseCell} | ${row.suiteExit} | ${row.revertExit} |`;
  }),
  "",
  ...sections,
];

writeFileSync(tablePath, lines.join("\n"));
