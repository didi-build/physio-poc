import { readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import AjvModule from "ajv";
import addFormatsModule from "ajv-formats";
import standaloneCode from "ajv/dist/standalone/index.js";

const __dirname = dirname(fileURLToPath(import.meta.url));
export const repoRoot = join(__dirname, "..", "..");
export const goldenPath = join(repoRoot, "test/fixtures/physio-mcp-tools.golden.json");
export const outDir = join(repoRoot, "src/services/mcp/generated");
export const outPath = join(outDir, "input-validators.js");
export const runtimeDir = join(outDir, "runtime");
export const ucs2VendorPath = join(runtimeDir, "ajv-ucs2length.js");
export const metaPath = join(outDir, "input-validator-meta.js");

const AJV_PKG = JSON.parse(
  readFileSync(join(repoRoot, "node_modules/ajv/package.json"), "utf8"),
);

const banner = `/* eslint-disable */
/* Generated by scripts/generate-mcp-input-validators.mjs - do not edit by hand. */
/* License: LICENSES/ajv-MIT.txt (Ajv standalone output). */
`;

export function buildAjvUcs2lengthVendorSource() {
  const upstream = readFileSync(
    join(repoRoot, "node_modules/ajv/dist/runtime/ucs2length.js"),
    "utf8",
  );
  const match = upstream.match(/function ucs2length\(str\) \{[\s\S]*?\n\}/);
  if (!match) {
    throw new Error("Unexpected ajv ucs2length upstream shape");
  }
  return `/* Vendored from ajv@${AJV_PKG.version} dist/runtime/ucs2length.js. Do not edit. */
/* License: LICENSES/ajv-MIT.txt */
export default ${match[0]};
`;
}

export function postProcessStandaloneSource(source) {
  let out = source;
  out = out.replace(
    /const func0 = require\("ajv\/dist\/runtime\/ucs2length"\)\.default;/g,
    "const func0 = ucs2length;",
  );
  if (out.includes("require(")) {
    throw new Error(
      "Generated validators still contain require(); adjust postProcessStandaloneSource.",
    );
  }
  const imports = `import ucs2length from "./runtime/ajv-ucs2length.js";
`;
  if (out.includes("formats0")) {
    throw new Error(
      "Unexpected date format in generated validators; reintroduce date vendor or adjust schemas.",
    );
  }
  return `${imports}${out}`;
}

function buildMetaSource() {
  return `/* Generated by scripts/generate-mcp-input-validators.mjs - do not edit by hand. */
export const DATE_FORMAT_FIELD_PATHS = new Set([]);
`;
}

function buildGeneratedSource() {
  const golden = JSON.parse(readFileSync(goldenPath, "utf8"));

  const Ajv = AjvModule.default ?? AjvModule;
  const addFormats = addFormatsModule.default ?? addFormatsModule;
  const ajv = new Ajv({
    allErrors: true,
    strict: false,
    validateFormats: true,
    validateSchema: false,
    code: { source: true, esm: true },
  });
  addFormats(ajv);

  const refs = {};
  for (const tool of golden) {
    const id = `physio-mcp-input/${tool.name}`;
    ajv.addSchema({ ...tool.inputSchema, $id: id });
    refs[tool.name] = id;
    ajv.compile({ $ref: id });
  }

  return `${banner}${postProcessStandaloneSource(standaloneCode(ajv, refs))}`;
}

export function buildAllGeneratedOutputs() {
  return {
    ucs2Vendor: buildAjvUcs2lengthVendorSource(),
    validators: buildGeneratedSource(),
    meta: buildMetaSource(),
  };
}

export function generatedOutputsMatchCommitted() {
  const expected = buildAllGeneratedOutputs();
  const committedUcs2 = readFileSync(ucs2VendorPath, "utf8");
  const committedMeta = readFileSync(metaPath, "utf8");
  const committedValidators = readFileSync(outPath, "utf8");
  return (
    committedUcs2 === expected.ucs2Vendor &&
    committedMeta === expected.meta &&
    committedValidators === expected.validators
  );
}
