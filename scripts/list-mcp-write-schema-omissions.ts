#!/usr/bin/env npx tsx
/**
 * Lists write-tool JSON Schema fields with no description (DIDI-1242) and HELD copy (DIDI-1251).
 * Run: npx tsx scripts/list-mcp-write-schema-omissions.ts
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { PHYSIO_MCP_TOOLS } from "../src/mcp-connector/index.js";
import { programRowInputSchema } from "../src/mcp-connector/json-schema.js";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");

const WRITE = new Set([
  "create_or_edit_program",
  "publish_program",
  "set_program_link_expiry",
  "delete_program",
]);

const OMITTED_TOOL_DESCRIPTIONS = [
  {
    tool: "create_or_edit_program",
    note: "No approved MCP tool description (#25–#27 in spec PR132 / DIDI-1251 cover publish, set expiry, and delete only).",
  },
] as const;

type Row = { tool: string; side: string; path: string };

function walk(
  node: unknown,
  prefix: string,
  out: Row[],
  tool: string,
  side: string,
): void {
  if (!node || typeof node !== "object") return;
  const n = node as Record<string, unknown>;
  if (n.properties && typeof n.properties === "object") {
    for (const [k, v] of Object.entries(n.properties as Record<string, unknown>)) {
      const p = prefix ? `${prefix}.${k}` : k;
      if (v && typeof v === "object") {
        const leaf = v as Record<string, unknown>;
        if (!Object.prototype.hasOwnProperty.call(leaf, "description")) {
          out.push({ tool, side, path: p });
        }
        walk(v, p, out, tool, side);
      }
    }
  }
  if (n.items) walk(n.items, `${prefix}[]`, out, tool, side);
  if (Array.isArray(n.oneOf)) for (const b of n.oneOf) walk(b, prefix, out, tool, side);
  if (Array.isArray(n.allOf)) for (const b of n.allOf) walk(b, prefix, out, tool, side);
}

const rows: Row[] = [];
for (const t of PHYSIO_MCP_TOOLS) {
  if (!WRITE.has(t.name)) continue;
  walk(t.inputSchema, "", rows, t.name, "input");
  walk(t.outputSchema, "", rows, t.name, "output");
}
walk(programRowInputSchema, "rows[]", rows, "create_or_edit_program", "input");

const seen = new Set<string>();
const unique = rows
  .filter((r) => {
    const k = `${r.tool}|${r.side}|${r.path}`;
    if (seen.has(k)) return false;
    seen.add(k);
    return true;
  })
  .sort(
    (a, b) =>
      a.tool.localeCompare(b.tool) ||
      a.side.localeCompare(b.side) ||
      a.path.localeCompare(b.path),
  );

const docDir = join(ROOT, "docs/mcp-connector");
mkdirSync(docDir, { recursive: true });
const outPath = join(docDir, "write-schema-omitted-descriptions.md");

let md = "# Write-tool schema fields without `description`\n\n";
md +=
  "Generated by `npx tsx scripts/list-mcp-write-schema-omissions.ts` from `PHYSIO_MCP_TOOLS` write tools. Read-tool schemas are unchanged.\n\n";
md +=
  "## Omitted MCP tool descriptions\n\nConfirm instruction is approved in tool descriptions #25–#27 (spec PR132, merge `5c02d0b`).\n\n";
for (const o of OMITTED_TOOL_DESCRIPTIONS) {
  md += `- \`${o.tool}\`: ${o.note}\n`;
}
md += "\n## Omitted schema `description` paths\n\n";
for (const r of unique) {
  md += `- \`${r.tool}\` ${r.side}: \`${r.path}\`\n`;
}
md += `\nTotal: ${unique.length} paths.\n`;

writeFileSync(outPath, md);
console.log(md);
